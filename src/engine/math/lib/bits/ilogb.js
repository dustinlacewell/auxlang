/**
 * floor(log2(x)) for a positive finite x, subnormals included: the binary
 * exponent, found by scaling with exact powers of two instead of reading bits.
 */
function ilogb(x) {
	let k = 0;
	let m = x;
	if (m < 2.2250738585072014e-308) {
		m *= 18014398509481984;
		k = -54;
	}
	if (m >= 2) {
		if (m >= 1.3407807929942597e154) {
			m *= 7.458340731200207e-155;
			k += 512;
		}
		if (m >= 1.157920892373162e77) {
			m *= 8.636168555094445e-78;
			k += 256;
		}
		if (m >= 3.402823669209385e38) {
			m *= 2.938735877055719e-39;
			k += 128;
		}
		if (m >= 1.8446744073709552e19) {
			m *= 5.421010862427522e-20;
			k += 64;
		}
		if (m >= 4294967296) {
			m *= 2.3283064365386963e-10;
			k += 32;
		}
		if (m >= 65536) {
			m *= 0.0000152587890625;
			k += 16;
		}
		if (m >= 256) {
			m *= 0.00390625;
			k += 8;
		}
		if (m >= 16) {
			m *= 0.0625;
			k += 4;
		}
		if (m >= 4) {
			m *= 0.25;
			k += 2;
		}
		if (m >= 2) k += 1;
		return k;
	}
	if (m < 1) {
		if (m < 1.4916681462400413e-154) {
			m *= 1.3407807929942597e154;
			k -= 512;
		}
		if (m < 1.727233711018889e-77) {
			m *= 1.157920892373162e77;
			k -= 256;
		}
		if (m < 5.877471754111438e-39) {
			m *= 3.402823669209385e38;
			k -= 128;
		}
		if (m < 1.0842021724855044e-19) {
			m *= 1.8446744073709552e19;
			k -= 64;
		}
		if (m < 4.656612873077393e-10) {
			m *= 4294967296;
			k -= 32;
		}
		if (m < 0.000030517578125) {
			m *= 65536;
			k -= 16;
		}
		if (m < 0.0078125) {
			m *= 256;
			k -= 8;
		}
		if (m < 0.125) {
			m *= 16;
			k -= 4;
		}
		if (m < 0.5) {
			m *= 4;
			k -= 2;
		}
		if (m < 1) k -= 1;
	}
	return k;
}
